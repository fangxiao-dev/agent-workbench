"""Batch evidence registration: JSON/JSONL add and multi-group carry-forward.

Kept out of engine.py; engine's command_evidence_add / command_evidence_carry_forward delegate here.
Private helpers are read through the engine module so tests can patch them there.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from impl_package_runtime import engine as e
from impl_package_runtime.engine import StateError
from situation import runtime_changed_files


def _add_one_evidence(
    package: Path, repo: Path, summary: dict[str, Any], state: dict[str, Any],
    comparison_commit: str, item: Any, results: list[dict[str, Any]],
) -> int:
    if isinstance(item, dict) and "recordedAt" in item:
        raise StateError("evidence recordedAt is generated by the runtime; omit it")
    evidence_key, record = e._normalize_journey_evidence(package, repo, summary, state, comparison_commit, item)
    # 逐条检查，批量失败时报错能点名是哪一行；整批终检仍在 e._validate_state
    e._package_relative_artifact(package, record["artifact"], "evidence artifact", must_exist=True)
    existing = state["evidenceIndex"].get(evidence_key, [])
    idempotent = any(
        {key: value for key, value in previous.items() if key != "recordedAt"}
        == {key: value for key, value in record.items() if key != "recordedAt"}
        for previous in existing
    )
    results.append({"evidenceKey": evidence_key, "idempotent": idempotent})
    if not idempotent:
        record["recordedAt"] = e._utc_timestamp()
        if record["kind"] == "journey-step":
            e._validate_journey_step_order(state, summary["_journeySpec"], record)
            e._validate_first_step_object_is_new(state, summary["_journeySpec"], record)
        state["evidenceIndex"].setdefault(evidence_key, []).append(record)
        return 1
    return 0


def _parse_evidence_input(payload_text: str) -> tuple[list[tuple[str, Any]], bool]:
    """Accept one JSON object, a JSON array, or JSON Lines; returns [(row label, item)] and whether it is a batch."""
    try:
        payload = json.loads(payload_text)
    except json.JSONDecodeError as exc:
        if payload_text.lstrip().startswith("["):
            raise StateError(f"evidence-add input is invalid JSON: {exc}") from exc
        rows: list[tuple[str, Any]] = []
        for number, line in enumerate(payload_text.splitlines(), start=1):
            if not line.strip():
                continue
            try:
                rows.append((f"line {number}", json.loads(line)))
            except json.JSONDecodeError as line_exc:
                raise StateError(f"evidence-add line {number} is invalid JSON: {line_exc}") from line_exc
        if not rows:
            raise StateError(f"evidence-add input is invalid JSON: {exc}") from exc
        return rows, True
    if isinstance(payload, dict):
        return [("record", payload)], False
    if isinstance(payload, list) and payload:
        return [(f"item {index}", item) for index, item in enumerate(payload, start=1)], True
    raise StateError("evidence-add input must be an object or non-empty array")


def evidence_add(package: Path, payload_text: str, dry_run: bool = False) -> dict[str, Any]:
    rows, is_batch = _parse_evidence_input(payload_text)
    items = [item for _, item in rows]
    state = e._load_json(package / e.STATE_PATH)
    summary = e._validate_state(package, state)
    e._assert_mutable(summary)
    repo = e._repo_root(package)
    results: list[dict[str, Any]] = []
    added = 0
    comparison_commit = e._run_git(repo, "rev-parse", "HEAD")
    for label, item in rows:
        try:
            added += _add_one_evidence(package, repo, summary, state, comparison_commit, item, results)
        except StateError as exc:
            if not is_batch:
                raise
            raise StateError(f"evidence-add {label}: {exc}（整批未写入）") from exc
    if dry_run:
        # 只读预检：用同一套校验跑完整批，不写 state。
        if added:
            e._validate_state(package, state, projections=False)
        return {"checked": len(items), "wouldAdd": added, "duplicates": len(items) - added}
    if added:
        e._validate_state(package, state, projections=False)
        e._write_json(package / e.STATE_PATH, state)
        e._refresh_projections(package, state)
    if not is_batch:
        return results[0]
    return {"records": results, "added": added, "duplicates": len(items) - added}


def _carry_forward_keys(state: dict[str, Any], selector: str) -> list[str]:
    """Evidence keys named by a selector that still have a supporting, non-invalidated record."""
    kind, _, value = selector.partition(":")
    if not value.strip():
        raise StateError(f"carry-forward selector {selector!r} must look like run:<id>, kind:suite|review, ticket:<id> or key:<key>")
    if kind == "run":
        match = lambda key: key == f"run-setup:{value}" or key.startswith(f"journey:{value}:")  # noqa: E731
    elif kind == "kind":
        if value not in {"suite", "review"}:
            raise StateError(f"carry-forward selector {selector!r}: kind must be suite or review")
        match = lambda key: key.startswith(f"{value}:")  # noqa: E731
    elif kind == "ticket":
        match = lambda key: key == f"review:{value}"  # noqa: E731
    elif kind == "key":
        match = lambda key: key == value  # noqa: E731
    else:
        raise StateError(f"carry-forward selector {selector!r} must start with run:, kind:, ticket: or key:")
    return [
        key for key, rows in state["evidenceIndex"].items()
        if match(key) and any(row.get("conclusion") == "supporting" and row.get("invalidatedBy") is None for row in rows)
    ]


def evidence_carry_forward(
    package: Path, key: str | None, to: str, reason: str | list[str] | None, judged_by: str,
    selects: list[str] | None = None, dry_run: bool = False,
) -> dict[str, Any]:
    """Record the agent's judgment that supporting evidence still covers runtime changes up to `to`.

    One call carries one or more (selector, reason) groups; state is validated once before and once after the loop,
    and nothing is written unless every group passes.
    """
    if key is not None and selects:
        raise StateError("evidence carry-forward takes either --key or --select, not both")
    legacy = key is not None
    if legacy:
        selects = [f"key:{key}"]
        reasons = [reason] if isinstance(reason, str) else list(reason or [])
    else:
        reasons = list(reason or []) if not isinstance(reason, str) else [reason]
    if not selects:
        raise StateError("evidence carry-forward requires --key or at least one --select")
    if len(selects) != len(reasons):
        raise StateError(f"evidence carry-forward needs one --reason per --select (got {len(selects)} select, {len(reasons)} reason)")
    if not isinstance(judged_by, str) or not judged_by.strip() or not all(
        isinstance(item, str) and item.strip() for item in (*reasons, *selects)
    ):
        raise StateError("evidence carry-forward requires non-empty --key/--select, --reason and --judged-by")
    state = e._load_json(package / e.STATE_PATH)
    summary = e._validate_state(package, state)
    e._assert_mutable(summary)
    repo = e._repo_root(package)
    target = e._validate_commit(repo, to)
    groups: list[tuple[str, str, list[str]]] = []
    assigned: dict[str, str] = {}
    for selector, group_reason in zip(selects, reasons):
        keys = _carry_forward_keys(state, selector)
        if not keys:
            raise StateError(
                f"evidence carry-forward group {selector!r} selects no key with a supporting, non-invalidated record to carry forward"
            )
        for item in keys:
            if item in assigned:
                raise StateError(f"evidence key {item} is selected by both {assigned[item]!r} and {selector!r}")
            assigned[item] = selector
        groups.append((selector, group_reason.strip(), keys))
    ancestry: dict[str, bool] = {}
    changed = 0
    for selector, group_reason, keys in groups:
        carried = {"to": target, "reason": group_reason, "judgedBy": judged_by.strip()}
        for item in keys:
            for record in state["evidenceIndex"][item]:
                if record.get("conclusion") != "supporting" or record.get("invalidatedBy") is not None:
                    continue
                revision = record["revision"]
                if revision not in ancestry:
                    ancestry[revision] = e._is_ancestor(repo, revision, target)
                if not ancestry[revision]:
                    raise StateError(
                        f"evidence carry-forward group {selector!r} key {item}: revision {revision[:7]} is not an ancestor of {target[:7]}（整批未写入）"
                    )
                if record.get("carriedForward") != carried:
                    record["carriedForward"] = dict(carried)
                    changed += 1
    package_rel = package.resolve().relative_to(repo).as_posix()
    runtime_files: dict[str, list[str] | None] = {}

    def changed_files(revision: str) -> list[str] | None:
        if revision not in runtime_files:
            runtime_files[revision] = runtime_changed_files(repo, package_rel, revision, target)
        return runtime_files[revision]

    if dry_run:
        report = []
        for selector, group_reason, keys in groups:
            files: set[str] = set()
            for item in keys:
                for record in state["evidenceIndex"][item]:
                    if record.get("conclusion") == "supporting" and record.get("invalidatedBy") is None:
                        files.update(changed_files(record["revision"]) or [])
            report.append({"select": selector, "reason": group_reason, "keys": keys, "runtimeChangedFiles": sorted(files)})
        return {"dryRun": True, "to": target, "groups": report}
    if changed:
        e._validate_state(package, state, projections=False)
        e._write_json(package / e.STATE_PATH, state)
        e._refresh_projections(package, state)
    if legacy:
        carried = {"to": target, "reason": groups[0][1], "judgedBy": judged_by.strip()}
        return {"evidenceKey": key, "carriedForward": carried, "idempotent": not changed}
    summary_files = {path for revision in {r["revision"] for _, _, ks in groups for k in ks for r in state["evidenceIndex"][k]} for path in changed_files(revision) or []}
    return {
        "to": target,
        "judgedBy": judged_by.strip(),
        "groups": [{"select": s_, "reason": r_, "keys": len(ks)} for s_, r_, ks in groups],
        "carriedKeys": len(assigned),
        "runtimeChangedFiles": len(summary_files),
        "idempotent": not changed,
    }
